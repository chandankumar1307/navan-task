-- =========================================================================
-- Navan Commerce: Multi-Modal Travel Inventory & Invoicing Database Schema
-- Idempotent ANSI DDL compatible with PostgreSQL 16+ and H2 (Postgres mode)
-- =========================================================================

CREATE TABLE IF NOT EXISTS transactions (
    id VARCHAR(36) NOT NULL PRIMARY KEY,
    external_id VARCHAR(128) NOT NULL UNIQUE,
    type VARCHAR(32) NOT NULL,
    currency VARCHAR(3) NOT NULL,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    total NUMERIC(12, 2) NOT NULL,
    metadata_json TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_txn_created_at ON transactions (created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS idx_txn_type ON transactions (type);

CREATE TABLE IF NOT EXISTS transaction_tax_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id VARCHAR(36) NOT NULL,
    name VARCHAR(128) NOT NULL,
    rate NUMERIC(6, 4),
    amount NUMERIC(12, 2) NOT NULL,
    CONSTRAINT fk_tax_transaction FOREIGN KEY (transaction_id) REFERENCES transactions (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_tax_txn_id ON transaction_tax_lines (transaction_id);

CREATE TABLE IF NOT EXISTS transaction_fee_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id VARCHAR(36) NOT NULL,
    name VARCHAR(128) NOT NULL,
    amount NUMERIC(12, 2) NOT NULL,
    CONSTRAINT fk_fee_transaction FOREIGN KEY (transaction_id) REFERENCES transactions (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_fee_txn_id ON transaction_fee_lines (transaction_id);

CREATE TABLE IF NOT EXISTS invoices (
    id VARCHAR(36) NOT NULL PRIMARY KEY,
    currency VARCHAR(3) NOT NULL,
    grand_total NUMERIC(12, 2) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_inv_created_at ON invoices (created_at DESC, id DESC);

CREATE TABLE IF NOT EXISTS invoice_transaction_snapshots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id VARCHAR(36) NOT NULL,
    original_transaction_id VARCHAR(36) NOT NULL,
    transaction_type VARCHAR(32) NOT NULL,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    total NUMERIC(12, 2) NOT NULL,
    metadata_json TEXT NOT NULL,
    CONSTRAINT fk_snapshot_invoice FOREIGN KEY (invoice_id) REFERENCES invoices (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_snapshot_invoice_id ON invoice_transaction_snapshots (invoice_id);
CREATE INDEX IF NOT EXISTS idx_snapshot_orig_txn_id ON invoice_transaction_snapshots (original_transaction_id);

CREATE TABLE IF NOT EXISTS invoice_tax_line_snapshots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    snapshot_id BIGINT NOT NULL,
    name VARCHAR(128) NOT NULL,
    rate NUMERIC(6, 4),
    amount NUMERIC(12, 2) NOT NULL,
    CONSTRAINT fk_tax_snapshot FOREIGN KEY (snapshot_id) REFERENCES invoice_transaction_snapshots (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_tax_snapshot_id ON invoice_tax_line_snapshots (snapshot_id);

CREATE TABLE IF NOT EXISTS invoice_fee_line_snapshots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    snapshot_id BIGINT NOT NULL,
    name VARCHAR(128) NOT NULL,
    amount NUMERIC(12, 2) NOT NULL,
    CONSTRAINT fk_fee_snapshot FOREIGN KEY (snapshot_id) REFERENCES invoice_transaction_snapshots (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_fee_snapshot_id ON invoice_fee_line_snapshots (snapshot_id);
